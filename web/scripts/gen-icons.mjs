// Builds src/components/ui/icon-registry.ts: every Ionicons name used as a string
// literal anywhere in src, imported one by one so the bundle only carries those.
// Run with `npm run icons` (also runs before dev and build).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

const require = createRequire(import.meta.url);
const icons = require('ionicons/icons');
const root = new URL('../src/', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const out = join(root, 'components/ui/icon-registry.ts');

const camel = (kebab) => kebab.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

function* files(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* files(path);
    else if (/\.(ts|tsx)$/.test(name) && path !== out) yield path;
  }
}

const used = new Set();
for (const file of files(root)) {
  for (const [, name] of readFileSync(file, 'utf8').matchAll(/['"`]([a-z][a-z0-9-]*)['"`]/g)) {
    if (icons[camel(name)]) used.add(name);
  }
}

const names = [...used].sort();
const source = `// Generated by scripts/gen-icons.mjs — do not edit.
import {
${names.map((n) => `  ${camel(n)},`).join('\n')}
} from 'ionicons/icons';

export const ICONS = {
${names.map((n) => `  '${n}': ${camel(n)},`).join('\n')}
} as const;
`;
writeFileSync(out, source);
console.log(`icon-registry: ${names.length} icons`);
